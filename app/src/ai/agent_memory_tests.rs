use super::*;

fn memory(
    name: Option<&str>,
    content: &str,
    root: Option<&str>,
    source: AIMemorySource,
) -> AIMemory {
    AIMemory {
        name: name.map(str::to_owned),
        content: content.to_owned(),
        is_autogenerated: false,
        suggested_logging_id: None,
        root_path: root.map(str::to_owned),
        source,
    }
}

#[test]
fn global_and_matching_project_memories_are_selected() {
    let memories = [
        memory(None, "global fact", None, AIMemorySource::Agent),
        memory(None, "app fact", Some("/work/app"), AIMemorySource::Agent),
        memory(None, "lib fact", Some("/work/lib"), AIMemorySource::Agent),
    ];

    let selected = select_memories(&memories, Some("/work/app"));

    assert_eq!(
        selected.global,
        vec![(AGENT_MEMORY_TITLE.to_owned(), "global fact".to_owned())]
    );
    assert_eq!(
        selected.project,
        Some(ProjectMemories {
            root_path: "/work/app".to_owned(),
            rules: vec![(AGENT_MEMORY_TITLE.to_owned(), "app fact".to_owned())],
        })
    );

    let outside_any_project = select_memories(&memories, None);
    assert_eq!(outside_any_project.global.len(), 1);
    assert_eq!(outside_any_project.project, None);
}

#[test]
fn memories_are_labelled_and_sorted() {
    let memories = [
        memory(Some("Style"), "Use tabs.", None, AIMemorySource::User),
        memory(None, "b", None, AIMemorySource::Agent),
        memory(None, "untitled", None, AIMemorySource::User),
        memory(None, "a", None, AIMemorySource::Agent),
    ];

    let selected = select_memories(&memories, None);

    assert_eq!(
        selected.global,
        vec![
            (AGENT_MEMORY_TITLE.to_owned(), "a".to_owned()),
            (AGENT_MEMORY_TITLE.to_owned(), "b".to_owned()),
            ("Rule".to_owned(), "untitled".to_owned()),
            ("Style".to_owned(), "Use tabs.".to_owned()),
        ]
    );
}

#[test]
fn blank_memories_are_skipped() {
    let memories = [
        memory(None, "  \n", None, AIMemorySource::User),
        memory(None, " ", Some("/work/app"), AIMemorySource::Agent),
    ];

    assert_eq!(
        select_memories(&memories, Some("/work/app")),
        RequestMemories::default()
    );
}

#[test]
fn an_existing_memory_is_found_by_trimmed_content_and_root() {
    let memories = [memory(
        None,
        " x ",
        Some("/work/app"),
        AIMemorySource::Agent,
    )];

    assert!(contains_memory(&memories, "x", Some("/work/app")));
    assert!(!contains_memory(&memories, "x", Some("/work/lib")));
    assert!(!contains_memory(&memories, "x", None));
    assert!(!contains_memory(&memories, "y", Some("/work/app")));
}

#[test]
fn a_remote_session_has_no_project_root() {
    warpui::App::test((), |app| async move {
        app.read(|ctx| {
            assert_eq!(
                project_root_for("/work/app", Some(&SessionType::WarpifiedRemote), ctx),
                None
            );
        });
    })
}
