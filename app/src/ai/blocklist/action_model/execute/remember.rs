/// The longest memory the agent may save, in characters. A memory is one fact, and every memory
/// is sent with every request.
const MAX_MEMORY_CHARS: usize = 2_000;

/// Saves a memory from the agent to the user's rules.
pub struct RememberExecutor {
    active_session: ModelHandle<ActiveSession>,
}

impl RememberExecutor {
    pub fn new(active_session: ModelHandle<ActiveSession>) -> Self {
        Self { active_session }
    }

    pub(super) fn should_autoexecute(&self, ctx: &mut ModelContext<Self>) -> bool {
        BlocklistAIPermissions::as_ref(ctx).can_write_memory(ctx)
    }

    pub(super) fn execute(
        &mut self,
        input: ExecuteActionInput,
        ctx: &mut ModelContext<Self>,
    ) -> impl Into<AnyActionExecution> + use<> {
        let AIAgentAction {
            action: AIAgentActionType::Remember { content, scope },
            ..
        } = input.action
        else {
            return ActionExecution::<()>::InvalidAction;
        };
        ActionExecution::Sync(AIAgentActionResultType::Remember(
            self.save(content, *scope, ctx),
        ))
    }

    fn save(
        &self,
        content: &str,
        scope: MemoryScope,
        ctx: &mut ModelContext<Self>,
    ) -> RememberResult {
        let is_memory_enabled = AISettings::as_ref(ctx).is_memory_enabled();
        let content = match validate_content(content, is_memory_enabled) {
            Ok(content) => content,
            Err(message) => return RememberResult::Error(message.to_owned()),
        };
        let root_path = match scope {
            MemoryScope::Global => None,
            MemoryScope::Project => {
                let session = self.active_session.as_ref(ctx);
                let session_type = session.session_type(ctx);
                if let Some(message) = remote_session_refusal(session_type.as_ref()) {
                    return RememberResult::Error(message.to_owned());
                }
                let project_root = session
                    .current_working_directory()
                    .and_then(|cwd| project_root_for(cwd, session_type.as_ref(), ctx));
                match project_root {
                    Some(root) => Some(root),
                    None => return RememberResult::Error(NO_PROJECT_MESSAGE.to_owned()),
                }
            }
        };

        log::debug!(
            "Saving an agent memory ({scope}, {} characters)",
            content.chars().count()
        );
        if contains_memory(saved_memories(ctx), content, root_path.as_deref()) {
            return RememberResult::Saved {
                project_root: root_path,
                already_saved: true,
            };
        }

        let fact = AIFact::Memory(AIMemory {
            name: None,
            content: content.to_owned(),
            is_autogenerated: false,
            suggested_logging_id: None,
            root_path: root_path.clone(),
            source: AIMemorySource::Agent,
        });
        UpdateManager::handle(ctx).update(ctx, |update_manager, ctx| {
            update_manager.create_ai_fact(fact, ClientId::default(), personal_drive(), ctx);
        });
        RememberResult::Saved {
            project_root: root_path,
            already_saved: false,
        }
    }

    pub(super) fn preprocess_action(
        &mut self,
        _action: PreprocessActionInput,
        _ctx: &mut ModelContext<Self>,
    ) -> BoxFuture<'static, ()> {
        futures::future::ready(()).boxed()
    }
}

impl Entity for RememberExecutor {
    type Event = ();
}

const NO_PROJECT_MESSAGE: &str = "The current directory is not inside a repository, so there is \
no project to remember this for. Use scope \"global\" if it applies to all projects.";

const REMOTE_SESSION_MESSAGE: &str = "This session runs on another machine, so there is no \
local project to remember this for. Use scope \"global\" if it applies to all projects.";

/// Why a project memory cannot be saved from a session of this type, if it cannot.
fn remote_session_refusal(session_type: Option<&SessionType>) -> Option<&'static str> {
    match session_type {
        Some(SessionType::WarpifiedRemote) => Some(REMOTE_SESSION_MESSAGE),
        None | Some(SessionType::Local) => None,
    }
}

/// The memory to save, trimmed, or why it cannot be saved. Nothing is saved while rules are off:
/// the tool is not offered then, so a call can only be a stale or invented one.
fn validate_content(content: &str, is_memory_enabled: bool) -> Result<&str, &'static str> {
    let content = content.trim();
    if !is_memory_enabled {
        Err("Memory is turned off.")
    } else if content.is_empty() {
        Err("The memory is empty.")
    } else if content.chars().count() > MAX_MEMORY_CHARS {
        Err("A memory must be one short fact (at most 2000 characters).")
    } else {
        Ok(content)
    }
}

