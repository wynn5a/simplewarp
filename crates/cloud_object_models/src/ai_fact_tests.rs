use super::*;

#[test]
fn an_old_memory_reads_as_a_global_user_rule() {
    let json = r#"{"memory":{"name":"Style","content":"Use tabs.","is_autogenerated":false}}"#;

    let AIFact::Memory(memory) = serde_json::from_str(json).expect("an old rule parses");

    assert_eq!(memory.root_path, None);
    assert_eq!(memory.source, AIMemorySource::User);
}

#[test]
fn a_global_user_rule_serializes_as_before() {
    let fact = AIFact::Memory(AIMemory {
        name: Some("Style".to_string()),
        content: "Use tabs.".to_string(),
        is_autogenerated: false,
        suggested_logging_id: None,
        root_path: None,
        source: AIMemorySource::User,
    });

    let json = serde_json::to_string(&fact).expect("a rule serializes");

    assert!(!json.contains("root_path"));
    assert!(!json.contains("source"));
}

#[test]
fn an_agent_memory_round_trips() {
    let fact = AIFact::Memory(AIMemory {
        name: None,
        content: "Tests run with cargo nextest.".to_string(),
        is_autogenerated: false,
        suggested_logging_id: None,
        root_path: Some("/work/app".to_string()),
        source: AIMemorySource::Agent,
    });

    let json = serde_json::to_string(&fact).expect("a rule serializes");

    assert_eq!(serde_json::from_str::<AIFact>(&json).unwrap(), fact);
}
